<p><b>Θεαίτητος</b>:</p>
<div class="trns max-h-24 overflow-y-auto bg-gray-100 px-4">

  ΣΩ. Εἰ μὲν τῶν ἐν Κυρήνῃ μᾶλλον ἐκηδόμην, ὦ Θεόδωρε, τὰ ἐκεῖ ἄν σε καὶ περὶ ἐκείνων ἀνηρώτων, εἴ τινες αὐτόθι περὶ γεωμετρίαν ἤ τινα ἄλλην φιλοσοφίαν εἰσὶ τῶν νέων ἐπιμέλειαν ποιούμενοι· νῦν δὲ ἧττον γὰρ ἐκείνους ἢ τούσδε φιλῶ, καὶ μᾶλλον ἐπιθυμῶ εἰδέναι τίνες ἡμῖν τῶν νέων ἐπίδοξοι γενέσθαι ἐπιεικεῖς. ταῦτα δὴ αὐτός τε σκοπῶ καθ' ὅσον δύναμαι, καὶ τοὺς ἄλλους ἐρωτῶ οἷς ἂν ὁρῶ τοὺς νέους ἐθέλοντας συγγίγνεσθαι. σοὶ δὴ οὐκ ὀλίγιστοι πλησιάζουσι, e  καὶ δικαίως· ἄξιος γὰρ τά τε ἄλλα καὶ γεωμετρίας ἕνεκα. εἰ δὴ οὖν τινι ἐνέτυχες ἀξίῳ λόγου, ἡδέως ἂν πυθοίμην.

    <br> ΘΕΟ. Καὶ μήν, ὦ Σώκρατες, ἐμοί τε εἰπεῖν καὶ σοὶ ἀκοῦσαι πάνυ ἄξιον οἵῳ ὑμῖν τῶν πολιτῶν μειρακίῳ ἐντετύχηκα. καὶ εἰ μὲν ἦν καλός, ἐφοβούμην ἂν σφόδρα λέγειν, μὴ καί τῳ δόξω ἐν ἐπιθυμίᾳ αὐτοῦ εἶναι. νῦν δέ—καὶ μή μοι ἄχθου—οὐκ ἔστι καλός, προσέοικε δὲ σοὶ τήν τε σιμότητα καὶ τὸ ἔξω τῶν ὀμμάτων· ἧττον δὲ ἢ σὺ ταῦτ' ἔχει. 144  ἀδεῶς δὴ λέγω. εὖ γὰρ ἴσθι ὅτι ὧν δὴ πώποτε ἐνέτυχον—καὶ πάνυ πολλοῖς πεπλησίακα—οὐδένα πω ᾐσθόμην οὕτω θαυμαστῶς εὖ πεφυκότα. τὸ γὰρ εὐμαθῆ ὄντα ὡς ἄλλῳ χαλεπὸν πρᾷον αὖ εἶναι διαφερόντως, καὶ ἐπὶ τούτοις ἀνδρεῖον παρ' ὁντινοῦν, ἐγὼ μὲν οὔτ' ἂν ᾠόμην γενέσθαι οὔτε ὁρῶ γιγνόμενον· ἀλλ' οἵ τε ὀξεῖς ὥσπερ οὗτος καὶ ἀγχίνοι καὶ μνήμονες ὡς τὰ πολλὰ καὶ πρὸς τὰς ὀργὰς ὀξύῤῥοποί εἰσι, καὶ ᾄττοντες φέρονται ὥσπερ τὰ ἀνερμάτιστα b  πλοῖα, καὶ μανικώτεροι ἢ ἀνδρειότεροι φύονται, οἵ τε αὖ ἐμβριθέστεροι νωθροί πως ἀπαντῶσι πρὸς τὰς μαθήσεις καὶ λήθης γέμοντες. ὁ δὲ οὕτω λείως τε καὶ ἀπταίστως καὶ ἀνυσίμως ἔρχεται ἐπὶ τὰς μαθήσεις τε καὶ ζητήσεις μετὰ πολλῆς πρᾳότητος, οἷον ἐλαίου ῥεῦμα ἀψοφητὶ ῥέοντος, ὥστε θαυμάσαι τὸ τηλικοῦτον ὄντα οὕτως ταῦτα διαπράττεσθαι.

    <br>ΣΩ. Εὖ ἀγγέλλεις. τίνος δὲ καὶ ἔστι τῶν πολιτῶν;

    <br>ΘΕΟ. Ἀκήκοα μὲν τοὔνομα, μνημονεύω δὲ οὔ. ἀλλὰ c  γάρ ἐστι τῶνδε τῶν προσιόντων ὁ ἐν τῷ μέσῳ· ἄρτι γὰρ ἐν τῷ ἔξω δρόμῳ ἠλείφοντο ἑταῖροί τέ τινες οὗτοι αὐτοῦ καὶ αὐτός, νῦν δέ μοι δοκοῦσιν ἀλειψάμενοι δεῦρο ἰέναι. ἀλλὰ σκόπει εἰ γιγνώσκεις αὐτόν.

    <br>ΣΩ. Γιγνώσκω· ὁ τοῦ Σουνιῶς Εὐφρονίου ἐστίν, καὶ πάνυ γε, ὦ φίλε, ἀνδρὸς οἷον καὶ σὺ τοῦτον διηγῇ, καὶ ἄλλως εὐδοκίμου, καὶ μέντοι καὶ οὐσίαν μάλα πολλὴν κατέλιπεν. τὸ δ' ὄνομα οὐκ οἶδα τοῦ μειρακίου.

    <br>d  ΘΕΟ. Θεαίτητος, ὦ Σώκρατες, τό γε ὄνομα· τὴν μέντοι οὐσίαν δοκοῦσί μοι ἐπίτροποί τινες διεφθαρκέναι. ἀλλ' ὅμως καὶ πρὸς τὴν τῶν χρημάτων ἐλευθεριότητα θαυμαστός, ὦ Σώκρατες.

    <br>ΣΩ. Γεννικὸν λέγεις τὸν ἄνδρα. καί μοι κέλευε αὐτὸν ἐνθάδε παρακαθίζεσθαι.

    <br>ΘΕΟ. Ἔσται ταῦτα. Θεαίτητε, δεῦρο παρὰ Σωκράτη.

